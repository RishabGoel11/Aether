"""
CLI command: aether team

Runs the collaborative multi-agent system (Planner, Researcher, Coder, Reviewer, Coordinator).

Usage
-----
    aether team "Design a Python CLI tool for checking site uptime"
    aether team "Analyze recent AI developments and write a summary script" --show-plan
"""

from __future__ import annotations

from app.bootstrap.builder import ApplicationBuilder


def team(goal: str, show_plan: bool = True) -> None:
    """
    Execute the multi-agent workflow for *goal* and print the synthesized deliverable.

    Parameters
    ----------
    goal:
        Overarching objective for the agent team to collaborate on.
    show_plan:
        If True, displays the structured execution plan generated by the Planner.
    """
    app = ApplicationBuilder().build()

    if not app.team:
        print("❌ Error: Multi-Agent team is not initialized.")
        return

    print(f"\n👥 Aether Multi-Agent Team assembling…\n   Goal: {goal}\n")
    print("─" * 60)

    result = app.team.solve(goal)

    if show_plan and result.plan:
        print("\n📋 Execution Plan:")
        print("─" * 60)
        print(result.plan.to_markdown())
        print("─" * 60)

    status = "✅ Team Workflow Complete" if result.success else "⚠️ Workflow Completed with Warnings"
    print(f"\n{status}\n")
    print("✨ Coordinator Final Deliverable:")
    print("─" * 60)
    print(result.final_answer)
    print("─" * 60)
